export const getPoseById = (id: string): PoseSuggestion => {
  return POSE_SUGGESTIONS.find((p) => p.id === id) || POSE_SUGGESTIONS[0];
};

export const getPosesByCategory = (category: string): PoseSuggestion[] => {
  if (category === 'all') return POSE_SUGGESTIONS;
  return POSE_SUGGESTIONS.filter((p) => p.category === category);
};

export const getRandomPose = (excludeId?: string): PoseSuggestion => {
  const filtered = POSE_SUGGESTIONS.filter((p) => p.id !== excludeId);
  const randomIndex = Math.floor(Math.random() * filtered.length);
  return filtered[randomIndex] || POSE_SUGGESTIONS[0];
};
